def apply_source_display_edits(source: str, text: str) -> str:
    lower = source.casefold()
    result = text
    if re.search(r"\b(?:wiring|electrical) plugs?\b|\bconnectors?\b", lower):
        result = re.sub(r"\b(?:проводн|штепсельн)\w* вилк\w*\b", "электрический разъём", result, flags=re.IGNORECASE)
    elif re.search(r"\bglow plugs?\b", lower):
        result = re.sub(r"\b(?:проводн|штепсельн)\w* вилк\w*\b", "свеча накаливания", result, flags=re.IGNORECASE)
    elif re.search(r"\bspark plugs?\b", lower):
        result = re.sub(r"\b(?:проводн|штепсельн)\w* вилк\w*\b", "свеча зажигания", result, flags=re.IGNORECASE)
    elif re.search(r"\bplugs?\b", lower):
        result = re.sub(r"\bштепсельн\w* вилк\w*\b", "пробка", result, flags=re.IGNORECASE)

    if re.search(r"\baerial leads?\b", lower):
        result = re.sub(r"\bвоздушн\w+ свинец\b", "антенный кабель", result, flags=re.IGNORECASE)
        result = re.sub(r"\bсвинец\b", "кабель", result, flags=re.IGNORECASE)
    elif re.search(r"\bleads?\b", lower) and not re.search(r"\b(?:leaded|unleaded)\b", lower):
        result = re.sub(r"\bHT свинц\w*\b", "высоковольтный провод", result, flags=re.IGNORECASE)
        result = re.sub(r"\bсвинц(?:а|у|ом|е)?\b", "провод", result, flags=re.IGNORECASE)
        result = re.sub(r"\bсвинцов(?:ый|ого|ому|ым|ом)\b", "проводной", result, flags=re.IGNORECASE)
        result = re.sub(r"\bсвинец\b", "провод", result, flags=re.IGNORECASE)
    if re.search(r"\brecover(?:ed|ing|s)?\b", lower):
        result = re.sub(r"\bдля (его|е[её]|их) восстановления\b", r"чтобы извлечь \1", result, flags=re.IGNORECASE)
        result = re.sub(r"\bвосстановите\b", "снимите", result, flags=re.IGNORECASE)
        result = re.sub(r"\bвосстановить\b", "снять", result, flags=re.IGNORECASE)
        result = re.sub(r"\bвосстанавливая\b", "снимая", result, flags=re.IGNORECASE)
        result = re.sub(r"\bвосстановит\b", "снимите", result, flags=re.IGNORECASE)
        result = re.sub(r"\bсохраните\b", "снимите", result, flags=re.IGNORECASE)
        result = re.sub(r"\bсохранить\b", "снять", result, flags=re.IGNORECASE)
    if re.search(r"\brenew(?:ed|ing|s|al)?\b", lower):
        result = re.sub(r"\bобновить\b", "заменить", result, flags=re.IGNORECASE)
