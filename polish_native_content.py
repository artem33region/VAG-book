def remove_unmatched_parentheses(text: str) -> str:
    chars = list(text)
    stack: list[int] = []
    remove: set[int] = set()
    for index, char in enumerate(chars):
        if char == "(":
            stack.append(index)
        elif char == ")":
            if stack:
                stack.pop()
            else:
                remove.add(index)
    remove.update(stack)
    return "".join(char for index, char in enumerate(chars) if index not in remove)


def clean_heading(text: str) -> str:
    text = re.sub(r"^[A-Za-z]{2,4}[-*®¢°.]?\d+\s+", "", text)
    text = re.sub(r"^(?:[A-Za-zА-Яа-я]{0,3}\d{1,3}[A-Za-zА-Яа-я®¢°*#.-]{1,6})\s+", "", text)
    text = re.sub(r"^(?:Глава\s+\d+(?:,\s*)?)", "", text, flags=re.IGNORECASE)
    exact = {
        "Удаление, осмотр": "Снятие, проверка и установка",
        "Удаление": "Снятие",
        "Переустановка": "Установка",
        "Ручная коробка передач": "Механическая коробка передач",
        "Обнаружение ошибок": "Поиск неисправностей",
    }
    return exact.get(text.strip(), text.strip())


def clean_text(source: str, translated: str, kind: str) -> str:
    text = html.unescape(translated).replace("\u00ad", "")
    text = text.replace("вЂ”", "—").replace("вЂ“", "—").replace("�", "")
    override = next(
        (replacement for pattern, replacement in SOURCE_TEXT_OVERRIDES if re.search(pattern, source, re.IGNORECASE)),
        None,
    )
    text = override if override is not None else enhance_translation(source, text)
    text = apply_source_display_edits(source, text)
    for pattern, replacement in DISPLAY_EDITS:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)
    for old, replacement in OPTIONAL_ENDING_EDITS:
        text = text.replace(old, replacement).replace(old.capitalize(), replacement.capitalize())

    # OCR checkbox/list furniture has no meaning in the native layout.
    text = re.sub(r"(?:\[\s*[|_\-]?\s*\]|\{\s*[|_\-]?\s*\}|[|_]\s*[\]}])", ". ", text)
    text = re.sub(r"(?:(?<=^)|(?<=[.!?:;]))\s*[\[\]{}|_\\]+\s*", " ", text)
    text = re.sub(r"[\[\]{}|_]", " ", text)
    text = re.sub(r"(?<=\w)[°¢®*#](?=\d)", "-", text)
    text = text.replace("©)", "в)").replace("©", "")
    text = remove_unmatched_parentheses(text)
    text = re.sub(r"\b([А-Яа-яЁё]{3,})\s+\1\b", r"\1", text, flags=re.IGNORECASE)
    text = re.sub(r"\bдвигатель\(ы\)\b", "двигатели", text, flags=re.IGNORECASE)
    text = re.sub(r"\bустройств(?:о)?\(ов\)\b", "устройства", text, flags=re.IGNORECASE)
    text = re.sub(r"\s+([,.;:!?])", r"\1", text)
    text = re.sub(r"([.!?])(?=[А-ЯЁ])", r"\1 ", text)
    text = re.sub(r"([,.;:!?])(?:\s*[,.!?]){1,}", r"\1", text)
    text = re.sub(r"\s*/\s*", "/", text)
    text = re.sub(r"\s{2,}", " ", text).strip(" \t,;:")
    if kind == "heading":
        text = clean_heading(text)
    if text:
        text = text[0].upper() + text[1:]
    return text


def is_damaged(text: str, source: str, kind: str) -> bool:
    if not text:
        return True
    cyrillic = len(re.findall(r"[А-Яа-яЁё]", text))
    meaningful = len(re.findall(r"[А-Яа-яЁёA-Za-z0-9]", text))
    if meaningful < 3 or cyrillic < 3:
        return True
    if re.search(r"\b(?:лоток мудрый|стрелено|чугудный|четырехглайзер|эйлинд|bseaking|systom)\b", text, re.IGNORECASE):
        return True
    if kind == "heading" and (len(text) < 3 or text.endswith((",", ";", " и", " в", " на", " для"))):
        return True
    if len(text) > 260 and not re.search(r"[.!?]", text):
        capitals = len(re.findall(r"(?:^|\s)[А-ЯЁ][а-яё]{2,}", text))
        if capitals >= 7:
            return True
    source_words = re.findall(r"[A-Za-z]{3,}", source)
    damaged_source = sum(
        bool(re.search(r"[^a-z]", word[1:-1])) or (word.isupper() and len(word) >= 7)
        for word in source_words
    )
    if len(source_words) >= 8 and damaged_source / len(source_words) > 0.34:
        return True
    return False


def split_long_block(block: dict[str, object], limit: int = 1150) -> list[dict[str, object]]:
    text = str(block.get("text", ""))
    if len(text) <= limit or block.get("type") == "heading":
        return [block]
    pieces = re.split(r"(?<=[.!?])\s+", text)
    output: list[dict[str, object]] = []
    current = ""
    for piece in pieces:
        candidate = f"{current} {piece}".strip()
        if current and len(candidate) > limit:
            item = dict(block)
            item["text"] = current
            output.append(item)
            current = piece
        else:
            current = candidate
    if current:
        item = dict(block)
        item["text"] = current
        output.append(item)
    if len(output) > 1:
        for position, item in enumerate(output):
            item["translationPart"] = position
    return output


def curated_article_blocks(
    slug: str,
    original: list[dict[str, object]],
) -> list[dict[str, object]]:
    prefix = [
        block
        for block in original
        if block.get("curated") and int(block.get("page", 0)) == 0
    ]
    images: dict[int, list[dict[str, object]]] = defaultdict(list)
    for block in original:
        if block.get("type") == "image" and not block.get("curated"):
            images[int(block.get("page", 0))].append(block)
    output = list(prefix)
    for page in sorted(set(CURATED_PAGES[slug]) | set(images)):
        for kind, text in CURATED_PAGES[slug].get(page, []):
            output.append({"type": kind, "page": page, "text": text, "curated": True})
        output.extend(images.get(page, []))
    return output


def polish(assets: Path, selected_slugs: set[str] | None = None) -> dict[str, int]:
    index_path = assets / "content_index.json"
    index = json.loads(index_path.read_text(encoding="utf-8"))
    stats = defaultdict(int)
    counts: dict[str, tuple[int, int]] = {}

    for section in index.get("sections", []):
        slug = str(section["slug"])
        if selected_slugs is not None and slug not in selected_slugs:
            continue
        path = assets / "articles" / f"{slug}.json"
        payload = json.loads(path.read_text(encoding="utf-8"))
        original = list(payload.get("blocks", []))
        source_counts = Counter(
            (block.get("page"), block.get("source"))
            for block in original if block.get("source")
        )

        if slug in CURATED_PAGES:
            blocks = curated_article_blocks(slug, original)
            stats["curated_sections"] += 1
        elif slug == "about":
            images = [block for block in original if block.get("type") == "image"]
            blocks = curated_about(images)
            stats["curated_sections"] += 1
        elif slug == "index":
            blocks = [block for block in original if block.get("curated") or block.get("type") == "image"]
            stats["index_blocks_removed"] += len(original) - len(blocks)
        else:
            blocks: list[dict[str, object]] = []
            for block in original:
                if (
                    block.get("type") == "image" or block.get("curated")
                    or "translationPart" in block
                    or (block.get("source") and source_counts[(block.get("page"), block.get("source"))] > 1)
                ):
                    blocks.append(block)
                    continue
                page = int(block.get("page", 0))
                if page in LAYOUT_PAGES:
                    stats["layout_blocks_removed"] += 1
                    continue
                source = str(block.get("source", ""))
                kind = str(block.get("type", "text"))
                text = clean_text(source, str(block.get("text", "")), kind)
                if kind == "heading" and (len(text) > 95 or re.match(r"^\d+\s+", text)):
                    kind = "text"
                    stats["headings_reclassified"] += 1
                if is_damaged(text, source, kind):
                    stats["damaged_blocks_removed"] += 1
                    continue
                item = dict(block)
                item["text"] = text
                item["type"] = kind
                pieces = split_long_block(item)
                blocks.extend(pieces)
                stats["blocks_split"] += len(pieces) - 1

        payload["blocks"] = blocks
        path.write_text(json.dumps(payload, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
        counts[slug] = (len(blocks), sum(block.get("type") == "image" for block in blocks))
        stats["articles_updated"] += 1

    for section in index.get("sections", []):
        slug = str(section["slug"])
        if slug not in counts:
            continue
        count = counts[slug]
        section["blockCount"], section["imageCount"] = count
    index_path.write_text(json.dumps(index, ensure_ascii=False, indent=2), encoding="utf-8")
    return dict(sorted(stats.items()))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", type=Path, default=DEFAULT_ASSETS)
    parser.add_argument(
        "--slug",
        action="append",
        help="Обрабатывать только указанный раздел; параметр можно повторять.",
    )
    args = parser.parse_args()
    selected_slugs = set(args.slug) if args.slug else None
    print(json.dumps(polish(args.assets, selected_slugs), ensure_ascii=False, indent=2))
    return 0


