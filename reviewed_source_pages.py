    for part in PAGES[(slug, page)].strip().split("\n\n"):
        kind = {"# ": "heading", "! ": "note", "> ": "caption"}.get(part[:2], "text")
        text = part[2:] if kind != "text" else part
        b = dict(type=kind, page=page, text=text, curated=True, layoutReviewed=True,
                 sourceReview="printed-pdf-v2")
        if kind == "text":
            if re.match(r"^\d+\. ", text):
                b["role"] = "legend" if "\n" in text else "steps"
            elif re.search(r"(?m)^(?:[a-z]\)|•) ", text):
                b["role"] = "bullets"
        blocks.append(b)
