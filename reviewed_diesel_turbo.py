def page_blocks(page):
    result = []
    for line in TEXT[page].strip().splitlines():
        kind = "heading" if line.startswith("# ") else "note" if line.startswith("! ") else "text"
        text = line[2:] if kind != "text" else line
        block = {"type": kind, "page": page, "text": text, "curated": True, "layoutReviewed": True}
        if re.match(r"^(?:•|[a-f]\)) ", text):
            block["role"] = "bullets"
        elif kind == "text" and re.match(r"^\d+ ", text):
            block["role"] = "steps"
        result.append(block)
    return result


