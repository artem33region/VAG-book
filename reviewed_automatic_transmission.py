def blocks():
    result = []
    for page, section, content in PAGES:
        for line in content.strip().splitlines():
            kind = "heading" if line.startswith("# ") else "note" if line.startswith("! ") else "text"
            text = line[2:] if kind != "text" else line
            item = {"type": kind, "page": page, "text": text, "curated": True,
                    "sourceSection": section}
            number = re.match(r"^(\d+) ", text) if kind == "text" else None
            if number:
                item["paragraph"] = int(number[1])
            result.append(item)
    return result
