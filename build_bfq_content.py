def resolve_patterns(patterns: Iterable[str]) -> list[str]:
    names: set[str] = set()
    for pattern in patterns:
        for path in SOURCE_MEDIA.glob(pattern):
            if path.is_file():
                names.add(path.name)
    return sorted(names)


def build() -> None:
    expected_parent = (ROOT / ".work" / "bfq").resolve()
    resolved_output = OUTPUT.resolve()
    if resolved_output.parent != expected_parent:
        raise RuntimeError(f"Unexpected output path: {resolved_output}")
    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    articles_dir = OUTPUT / "articles"
    media_dir = OUTPUT / "media"
    articles_dir.mkdir(parents=True)
    media_dir.mkdir(parents=True)

    index_sections: list[dict[str, object]] = []
    copied: set[str] = set()
    total_blocks = 0
    total_images = 0

    for section in SECTIONS:
        blocks = list(section["blocks"])
        asset_names = list(section.get("images", []))
        asset_names.extend(resolve_patterns(section.get("patterns", [])))
        description = str(section.get("image_description", "Иллюстрация к операции"))
        if asset_names:
            blocks.append(heading("Иллюстрации"))
        for asset_name in asset_names:
            source = SOURCE_MEDIA / asset_name
            if not source.is_file():
                raise FileNotFoundError(source)
            if asset_name not in copied:
                shutil.copy2(source, media_dir / asset_name)
                copied.add(asset_name)
            block = image(asset_name, description)
            match = re.search(r"_(\d{4})_\d{2}\.webp$", asset_name)
            if match:
                full_page = f"source/haynes_{match[1]}.webp"
                if (SOURCE_MEDIA / full_page).is_file():
                    (media_dir / "source").mkdir(exist_ok=True)
                    shutil.copy2(SOURCE_MEDIA / full_page, media_dir / full_page)
                    block["sourceAsset"] = f"media/{full_page}"
            blocks.append(block)

        payload = {
            "code": section["code"],
            "slug": section["slug"],
            "category": section["category"],
            "title": section["title"],
            "startPage": 0,
            "endPage": 0,
            "blocks": blocks,
        }
        article_path = articles_dir / f"{section['slug']}.json"
        article_path.write_text(
            json.dumps(payload, ensure_ascii=False, separators=(",", ":")),
            encoding="utf-8",
        )
        image_count = sum(block.get("type") == "image" for block in blocks)
        index_sections.append(
            {
                "code": section["code"],
                "slug": section["slug"],
                "category": section["category"],
                "title": section["title"],
                "startPage": 0,
                "endPage": 0,
                "blockCount": len(blocks),
                "imageCount": image_count,
            }
        )
        total_blocks += len(blocks)
        total_images += image_count

    index = {
        "title": "VW BFQ 1.6 — сервисный справочник",
        "format": "native-article-v1",
        "sections": index_sections,
    }
    (OUTPUT / "content_index.json").write_text(
        json.dumps(index, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(
        json.dumps(
            {
                "sections": len(index_sections),
                "blocks": total_blocks,
                "image_blocks": total_images,
                "unique_media": len(copied),
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    build()
