def h(value):
    return {"type": "heading", "text": value}


def t(value):
    return {"type": "text", "text": value}


def n(value):
    return {"type": "note", "text": value}


def steps(*values):
    return {"type": "text", "role": "steps", "text": "\n\n".join(
        f"{i}. {value}" for i, value in enumerate(values, 1))}


def items(*values):
    return {"type": "text", "role": "bullets", "text": "\n".join(f"• {v}" for v in values)}


def plate(page, caption, box=None):
    # Boxes use pixels in the reviewed 1.5x page rendering. No masking/retouching.
    return {"page": page, "caption": caption, "box": box}


def section(code, slug, category, title, pages, blocks, plates=()):
    return dict(code=code, slug=slug, category=category, title=title,
                sourcePages=pages, blocks=blocks, plates=list(plates))


