def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")


def build(output=ASSETS):
    # No cleanup of arbitrary directories. The audit detects obsolete assets.
    import pymupdf
    from PIL import Image
    from translate_haynes import DEFAULT_INPUT

    output = Path(output)
    (output / "media/source").mkdir(parents=True, exist_ok=True)
    provenance = []
    index = []
    with pymupdf.open(DEFAULT_INPUT) as pdf:
        for row in SECTIONS:
            blocks = [dict(block, page=row["sourcePages"][0]) for block in row["blocks"]]
            blocks.append({"type": "caption", "page": row["sourcePages"][0],
                           "text": "Источник: Haynes, страницы PDF " + ", ".join(map(str, row["sourcePages"])) + "."})
            for pos, picture in enumerate(row["plates"], 1):
                page = picture["page"]
                source_asset = f"media/source/haynes_{page:04d}.webp"
                source_path = output / source_asset
                if not source_path.exists():
                    shared = SOURCE / "source" / source_path.name
                    if shared.exists():
                        shutil.copy2(shared, source_path)
                    else:
                        pix = pdf[page - 1].get_pixmap(matrix=pymupdf.Matrix(2, 2))
                        Image.frombytes("RGB", (pix.width, pix.height), pix.samples).save(source_path, quality=88, method=4)
                box = picture["box"]
                asset = source_asset
                if box:
                    asset = f"media/bca_{row['slug']}_{pos:02d}.webp"
                    pix = pdf[page - 1].get_pixmap(matrix=pymupdf.Matrix(1.5, 1.5))
                    original = Image.frombytes("RGB", (pix.width, pix.height), pix.samples)
                    if not (0 <= box[0] < box[2] <= original.width and 0 <= box[1] < box[3] <= original.height):
                        raise ValueError(f"Invalid crop on page {page}: {box}")
                    original.crop(box).save(output / asset, quality=88, method=4)
                blocks.append(dict(type="image", page=page, asset=asset,
                                   description=picture["caption"], sourceAsset=source_asset if box else ""))
                provenance.append(dict(asset=asset, page=page, box=box, sourceAsset=source_asset))
            common = {key: row[key] for key in ("code", "slug", "category", "title", "sourcePages")}
            common.update(startPage=0, endPage=0)
            write_json(output / "articles" / f"{row['slug']}.json", dict(common, blocks=blocks))
            index.append(dict(common, blockCount=len(blocks), imageCount=len(row["plates"])))
    write_json(output / "content_index.json", dict(title="VW BCA 1.4 16V — сервисный справочник", format="native-article-v1", sections=index))
    # Kept beside the builder, not in app assets; it is a reviewer/build artifact.
    if output.resolve() == ASSETS.resolve():
        write_json(ROOT / "bca_image_provenance.json", dict(scale=1.5, source=str(DEFAULT_INPUT.name), images=provenance))
        template = (ROOT / "android-bfq/app/src/main/java/ru/vagguides/golf4manual/ManualSections.java").read_text(encoding="utf-8")
        start = template.index("            new Section(")
        end = template.index("\n    ));", start)
        declarations = ",\n".join("            new Section(" + ", ".join(json.dumps(r[k], ensure_ascii=False) for k in ("code", "slug", "category", "title")) + ", 0, 0)" for r in SECTIONS)
        (ROOT / "android-bca/app/src/main/java/ru/vagguides/golf4manual/ManualSections.java").write_text(template[:start] + declarations + template[end:], encoding="utf-8", newline="\n")
    print(json.dumps(dict(sections=len(index), blocks=sum(r["blockCount"] for r in index), images=len(provenance)), indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ASSETS)
    build(parser.parse_args().output)
