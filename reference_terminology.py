def _apply_edits(text: str, edits: Sequence[Edit]) -> str:
    result = text
    for pattern, replacement in edits:
        result = re.sub(pattern, replacement, result, flags=re.IGNORECASE)
    return result


def enhance_translation(source: str, translated: str) -> str:
    normalized = re.sub(r"\s+", " ", source).strip().casefold()
    exact = EXACT_TRANSLATIONS.get(normalized)
    if exact is not None:
        return exact

    result = _apply_edits(translated, GLOBAL_EDITS)
    for source_pattern, edits in SOURCE_EDITS:
        if re.search(source_pattern, source, flags=re.IGNORECASE):
            result = _apply_edits(result, edits)

    result = re.sub(r"\s+([,.;:!?])", r"\1", result)
    result = re.sub(r"\s{2,}", " ", result).strip()
    if result:
        result = result[0].upper() + result[1:]
    return result
