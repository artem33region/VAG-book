def curate(assets: Path) -> dict[str, int]:
    index_path = assets / "content_index.json"
    index = json.loads(index_path.read_text(encoding="utf-8"))
    updated = 0
    for section in index.get("sections", []):
        slug = str(section["slug"])
        path = assets / "articles" / f"{slug}.json"
        payload = json.loads(path.read_text(encoding="utf-8"))
        original = [block for block in payload.get("blocks", []) if not block.get("curated")]
        if slug == "about":
            images = [block for block in original if block.get("type") == "image" and int(block.get("page", 0)) >= 8]
            blocks = curated_about(images)
        else:
            intro = INTROS.get(slug, f"Материалы по разделу «{section['title']}»: диагностика, снятие, проверка и установка деталей.")
            blocks = [
                {"type": "heading", "page": 0, "text": section["title"], "curated": True},
                {"type": "text", "page": 0, "text": intro, "curated": True},
                {"type": "note", "page": 0, "text": GENERAL_NOTE, "curated": True},
                *original,
            ]
        payload["blocks"] = blocks
        path.write_text(json.dumps(payload, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
        section["blockCount"] = len(blocks)
        section["imageCount"] = sum(block.get("type") == "image" for block in blocks)
        updated += 1
    index_path.write_text(json.dumps(index, ensure_ascii=False, indent=2), encoding="utf-8")
    return {"sections_updated": updated}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", type=Path, default=DEFAULT_ASSETS)
    args = parser.parse_args()
    print(json.dumps(curate(args.assets), ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
